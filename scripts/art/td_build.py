# Top-down building sprites: width = footprint tiles x 64 px (2x density), bottom = slab bottom.
# Sources: art-src/gpt/topdown/plants/<id>_L<n>.png (one GPT picture per level, magenta
# background) and, for buildings without those yet, the older level-1 cut-outs in td/s.
import os, glob, re, numpy as np
from PIL import Image
R = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
OLD = '/home/claude/art/td/s'
OLDMAP = {'cdu': ('cdu', 2), 'crude': ('crudeTank', 2), 'tank': ('tank', 1), 'blend': ('blend', 2), 'loading': ('loading', 2), 'lab': ('lab', 1)}
TILES = {'gate': 1, 'loading': 2, 'crudeTank': 2, 'tank': 1, 'cdu': 2, 'blend': 2, 'pipe': 1, 'hydro': 2,
         'lab': 1, 'reformer': 2, 'cracker': 3, 'control': 2, 'canteen': 2, 'flare': 1, 'tower': 3}

def key(im):
    a = np.array(im.convert('RGBA')).astype(int)
    r, g, b = a[..., 0], a[..., 1], a[..., 2]
    bg = (r > 150) & (b > 150) & (g < 120) & (np.abs(r - b) < 80)
    a[bg] = 0
    # Warm beige slab -> the yard's neutral grey, same brightness.
    lum = (r + g + b) / 3
    beige = (~bg) & (r - b > 18) & (r - b < 50) & (g - b > 8) & (lum > 120) & (np.abs(r - g) < 22)
    for c, d in ((0, -2), (1, 0), (2, 3)):
        a[..., c] = np.where(beige, np.clip(lum + d, 0, 255), a[..., c])
    return Image.fromarray(a.astype('uint8'))

def slab_span(im):
    m = np.array(im)[..., 3] > 0; ys = np.nonzero(m.any(1))[0]
    xs = np.nonzero(m[ys.max() - 6:ys.max()].any(0))[0]
    return xs.min(), xs.max() + 1

def fit(im, w, span):
    f = (w * 64) / (span[1] - span[0])
    out = im.resize((round(im.width * f), round(im.height * f)), Image.LANCZOS)
    b = np.array(out); b[..., 3] = np.where(b[..., 3] > 110, 255, 0)
    return Image.fromarray(b), (span[0] + span[1]) / 2 * f

meta = {}
for src, (id, w) in OLDMAP.items():
    im = Image.open(f'{OLD}/{src}.png').convert('RGBA'); im = im.crop(im.getbbox())
    out, cx = fit(im, w, slab_span(im))
    out.save(f'{R}/assets/v4/td/{id}_L1.png')
    meta[id] = {1: dict(w=out.width, h=out.height, ax=round(cx, 1), ay=out.height)}
new = {}
for p in glob.glob(f'{R}/art-src/gpt/topdown/plants/*_L[1-5].png'):
    id, lv = re.match(r'(\w+)_L(\d)\.png', os.path.basename(p)).groups()
    new.setdefault(id, {})[int(lv)] = p
for id, levels in new.items():
    w = TILES[id]; meta[id] = {}
    for f in glob.glob(f'{R}/assets/v4/td/{id}_L*.png'): os.remove(f)
    for lv, p in sorted(levels.items()):
        im = key(Image.open(p)); im = im.crop(im.getbbox())
        out, cx = fit(im, w, slab_span(im))
        out.save(f'{R}/assets/v4/td/{id}_L{lv}.png', optimize=True)
        meta[id][lv] = dict(w=out.width, h=out.height, ax=round(cx, 1), ay=out.height)
        print(id, lv, out.size)
lines = ["// Top-down building art (GPT), generated by scripts/art/td_build.py.",
         "// Each image is footprint-tiles x 64 px wide (2x density); (ax, ay) is the slab's bottom centre.",
         "import type { SpriteImage } from './spriteImages'",
         "export const tdBuildings: Record<string, Partial<Record<1 | 2 | 3 | 4 | 5, SpriteImage>>> = {"]
for id, levels in meta.items():
    lines.append(f"  {id}: {{")
    for lv, m in sorted(levels.items()):
        lines.append(f"    {lv}: {{ src: require('../../../assets/v4/td/{id}_L{lv}.png'), w: {m['w']}, h: {m['h']}, ax: {m['ax']}, ay: {m['ay']}, scale: 1, smooth: true }},")
    lines.append("  },")
lines.append("}")
open(f'{R}/src/v4/render/tdBuildings.ts', 'w').write("\n".join(lines) + "\n")
