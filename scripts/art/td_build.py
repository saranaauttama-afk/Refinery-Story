# Top-down building sprites: width = footprint tiles x 64 px (2x density), bottom = slab bottom.
import json, os, numpy as np
from PIL import Image
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..') if os.path.exists(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'app.json')) else '/home/claude/refinery-story'
SRC = 'td/s'
MAP = {'cdu': ('cdu', 2), 'crude': ('crudeTank', 2), 'tank': ('tank', 1), 'blend': ('blend', 2), 'loading': ('loading', 2), 'lab': ('lab', 1)}
meta = {}
for src, (id, w) in MAP.items():
    im = Image.open(f'{SRC}/{src}.png').convert('RGBA'); im = im.crop(im.getbbox())
    # slab width = widest opaque span in the bottom rows
    a = np.array(im); m = a[:, :, 3] > 0; ys = np.nonzero(m.any(1))[0]
    xs = np.nonzero(m[ys.max() - 6:ys.max()].any(0))[0]; slab = xs.max() - xs.min() + 1
    f = (w * 64) / slab
    out = im.resize((round(im.width * f), round(im.height * f)), Image.LANCZOS)
    b = np.array(out); b[:, :, 3] = np.where(b[:, :, 3] > 110, 255, 0); out = Image.fromarray(b)
    cx = (xs.min() + xs.max() + 1) / 2 * f
    out.save(f'{R}/assets/v4/td/{id}_L1.png')
    meta[id] = dict(w=out.width, h=out.height, ax=round(cx, 1), ay=out.height, tiles=w)
    print(id, out.size)
lines = ["// Top-down building art (GPT), generated by scripts/art/td_build.py.",
         "// Each image is footprint-tiles x 64 px wide (2x density); (ax, ay) is the slab's bottom centre.",
         "import type { SpriteImage } from './spriteImages'",
         "export const tdBuildings: Record<string, Partial<Record<1 | 2 | 3 | 4 | 5, SpriteImage>>> = {"]
for id, m in meta.items():
    lines.append(f"  {id}: {{ 1: {{ src: require('../../../assets/v4/td/{id}_L1.png'), w: {m['w']}, h: {m['h']}, ax: {m['ax']}, ay: {m['ay']}, scale: 1, smooth: true }} }},")
lines.append("}")
open(f'{R}/src/v4/render/tdBuildings.ts', 'w').write("\n".join(lines) + "\n")
