// Prepare generated decoration sprites at the world's native 64 art pixels/tile.
import fs from 'node:fs'
import crypto from 'node:crypto'
import sharp from 'sharp'
import { yardDecor } from '../../src/v4/data/yardDecor'
const root = 'assets/v5/yard'
async function main() {
  const source = fs.readFileSync(`${root}/source/decor.png`)
  const { data, info } = await sharp(source)
    .ensureAlpha()
    .raw()
    .toBuffer({ resolveWithObject: true })
  const W = info.width,
    H = info.height,
    seen = new Uint8Array(W * H)
  const groups: number[][][] = Array.from({ length: 12 }, () => [])
  for (let n = 0; n < W * H; n++) {
    if (seen[n] || data[n * 4 + 3] < 180) continue
    const pixels = [n]
    seen[n] = 1
    let left = W,
      right = 0,
      top = H,
      bottom = 0
    for (let j = 0; j < pixels.length; j++) {
      const p = pixels[j],
        x = p % W,
        y = Math.floor(p / W)
      left = Math.min(left, x)
      right = Math.max(right, x)
      top = Math.min(top, y)
      bottom = Math.max(bottom, y)
      for (let dy = -1; dy <= 1; dy++)
        for (let dx = -1; dx <= 1; dx++) {
          const xx = x + dx,
            yy = y + dy,
            q = yy * W + xx
          if (xx < 0 || xx >= W || yy < 0 || yy >= H || seen[q] || data[q * 4 + 3] < 180) continue
          seen[q] = 1
          pixels.push(q)
        }
    }
    if (pixels.length < 40) continue
    const col = Math.min(2, Math.floor((((left + right) / 2) * 3) / W)),
      row = Math.min(3, Math.floor((((top + bottom) / 2) * 4) / H))
    groups[row * 3 + col].push(pixels)
  }
  fs.mkdirSync(`${root}/sprites`, { recursive: true })
  const manifest: Record<string, unknown> = {},
    registry: string[] = []
  for (const [i, d] of yardDecor.entries()) {
    const largest = Math.max(...groups[i].map(p => p.length))
    const pixels = groups[i].filter(p => p.length > Math.max(40, largest * 0.005)).flat()
    if (!pixels.length) throw Error(`Missing decoration ${d.id}`)
    let left = W,
      right = 0,
      top = H,
      bottom = 0
    for (const p of pixels) {
      left = Math.min(left, p % W)
      right = Math.max(right, p % W)
      top = Math.min(top, Math.floor(p / W))
      bottom = Math.max(bottom, Math.floor(p / W))
    }
    const w = right - left + 1,
      h = bottom - top + 1,
      raw = Buffer.alloc(w * h * 4)
    for (const p of pixels) {
      const dest = ((Math.floor(p / W) - top) * w + (p % W) - left) * 4
      data.copy(raw, dest, p * 4, p * 4 + 3)
      raw[dest + 3] = 255
    }
    const artWidth = d.artWidth,
      k = artWidth / w,
      artHeight = Math.round(h * k),
      width = 80,
      height = Math.max(72, artHeight + 8),
      ax = 40,
      ay = height - 4
    const sprite = await sharp(raw, { raw: { width: w, height: h, channels: 4 } })
      .resize(artWidth, artHeight, { kernel: 'nearest' })
      .toBuffer()
    const file = `${d.id}.png`
    await sharp({
      create: { width, height, channels: 4, background: { r: 0, g: 0, b: 0, alpha: 0 } },
    })
      .composite([
        {
          input: sprite,
          raw: { width: artWidth, height: artHeight, channels: 4 },
          left: Math.round((width - artWidth) / 2),
          top: ay - artHeight,
        },
      ])
      .png({ palette: true, colours: 96, dither: 0 })
      .toFile(`${root}/sprites/${file}`)
    manifest[d.id] = { file, width, height, ax, ay, scale: 0.5, footprint: { w: 1, h: 1 } }
    registry.push(
      `  ${d.id}: { 1: { src: require('../../../${root}/sprites/${file}'), w: ${width}, h: ${height}, ax: ${ax}, ay: ${ay}, scale: 0.5, smooth: false } },`,
    )
  }
  fs.writeFileSync(`${root}/manifest.json`, JSON.stringify(manifest, null, 2) + '\n')
  fs.writeFileSync(
    `${root}/source/SHA256.json`,
    JSON.stringify(
      { 'decor.png': crypto.createHash('sha256').update(source).digest('hex') },
      null,
      2,
    ) + '\n',
  )
  fs.writeFileSync(
    'src/v4/render/yardDecorSprites.ts',
    `// Generated by npm run art:yard. Source and prompts: assets/v5/yard/source.\nexport const yardDecorSprites = {\n${registry.join('\n')}\n}\n`,
  )
  console.log('12 generated one-tile yard decorations ready')
}
main().catch(e => {
  console.error(e)
  process.exit(1)
})
