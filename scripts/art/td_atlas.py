# Top-down world atlas -> assets/v4/td/world.png + src/v4/render/tdAtlas.ts
# Entry: [x, y, w, h, ax, ay, k] where k = world px per atlas px (1 tile = 32 world px).
import os, numpy as np
from PIL import Image
R='/home/claude/refinery-story'
items={}
def add(n,im,ax,ay,k): items[n]=(im.convert('RGBA'),ax,ay,k)
T=Image.open('gptprops/sheet6.png').convert('RGB'); W,H=T.size; cw,ch=W//3,H//2
names=['concrete','asphalt','quay','grass','sand','water']
def dull(im):
    a=np.array(im).astype(float); g=a[:,:,:3].mean(2,keepdims=True); a[:,:,:3]=np.clip((a[:,:,:3]*0.8+g*0.2)*0.86,0,255); return Image.fromarray(a.astype('uint8'))
for k,n in enumerate(names):
    c=T.crop(((k%3)*cw+6,(k//3)*ch+6,(k%3+1)*cw-6,(k//3+1)*ch-6)).resize((128,128),Image.LANCZOS).convert('RGBA')
    for i in (0,1):
        for j in (0,1):
            t=c.crop((i*64,j*64,i*64+64,j*64+64)); add(f'tex_{n}{i}{j}',t,0,0,0.5)
            if n=='grass': add(f'tex_locked{i}{j}',dull(t),0,0,0.5)
def trim(p):
    im=Image.open(p).convert('RGBA'); return im.crop(im.getbbox())
for g,n in [('tree',7),('palm',5),('bush',4),('cloud',5),('gull',2),('fish',1),('rocks',4)]:
    for i in range(n):
        im=trim(f'pick/{g}_{i}.png'); add(f'{g}{i}',im,im.width/2,im.height-1 if g in('tree','palm','bush','rocks') else im.height/2,1)
for v in ['crude','product','car','ship','fishboat']:
    for d in ['east','west','north','south']:
        im=trim(f'r7/{v}/rotation_urls_{d}.png'); add(f'{v}_{d}',im,im.width/2,im.height*0.62,1)
def frames(path,fw,fh,nf,prefix,ax,ay):
    sh=Image.open(path).convert('RGBA'); cols=sh.width//fw
    for i in range(nf): add(f'{prefix}{i}',sh.crop(((i%cols)*fw,(i//cols)*fh,(i%cols+1)*fw,(i//cols+1)*fh)),ax,ay,1)
frames('r8/smoke/chimney-smoke.png',32,32,16,'smoke',14,31)
frames('r8/sparkle/level-up-sparkle.png',48,48,8,'spark',24,24)
names=sorted(items,key=lambda n:-items[n][0].height); AW=1024; x=y=rowh=0; rects={}
for n in names:
    im=items[n][0]
    if x+im.width+1>AW: x=0; y+=rowh+1; rowh=0
    rects[n]=(x,y); x+=im.width+1; rowh=max(rowh,im.height)
atlas=Image.new('RGBA',(AW,y+rowh),(0,0,0,0))
for n,(px,py) in rects.items(): atlas.alpha_composite(items[n][0],(px,py))
atlas.save(f'{R}/assets/v4/td/world.png',optimize=True)
L=["// Generated by scripts/art/td_atlas.py: top-down world sprites in one image.",
   "// [x, y, w, h, ax, ay, k]: atlas rect, anchor, world px per atlas px (1 tile = 32).",
   "export const tdAtlasSrc = require('../../../assets/v4/td/world.png')",
   "export const tdAtlas: Record<string, readonly [number, number, number, number, number, number, number]> = {"]
for n in sorted(rects):
    im,ax,ay,k=items[n]; px,py=rects[n]; L.append(f"  {n}: [{px}, {py}, {im.width}, {im.height}, {round(ax,1)}, {round(ay,1)}, {k}],")
L.append("}")
open(f'{R}/src/v4/render/tdAtlas.ts','w').write("\n".join(L)+"\n"); print(atlas.size,len(rects))
