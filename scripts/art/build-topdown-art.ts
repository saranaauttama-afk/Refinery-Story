// Reproducible source -> native-resolution PNGs. No image resizing or AI sheet cutting.
import fs from 'node:fs'
import path from 'node:path'
import { createRequire } from 'node:module'
import CanvasKitInit from 'canvaskit-wasm/full'
import { buildings } from '../../src/v4/data/buildings'
import { topdownArt, artDefinition } from '../../src/v4/render/topdownArt'
import { spriteTemplate, scenicSizes, buildingSocket } from '../../src/v4/render/graphics'
const require = createRequire(import.meta.url)
async function main() {
  const ck = await CanvasKitInit({
    locateFile: f => path.join(path.dirname(require.resolve('canvaskit-wasm/full')), f),
  })
  const root = process.cwd(),
    target = path.join(root, 'assets/v5/buildings')
  fs.mkdirSync(target, { recursive: true })
  const registry: string[] = [
    '// Generated by npm run art:v5. Final pixels are world units; no hidden density factor.',
    "import type { SpriteImage, Tier } from './spriteImages'",
    'export const v5Buildings: Record<string, Partial<Record<Tier, SpriteImage>>> = {',
  ]
  const manifest: Record<string, unknown> = {}
  const variants = [
    ...buildings.flatMap(d => [d.id, ...(d.id === 'gate' ? ['gate_w'] : [])]),
    ...Object.keys(scenicSizes),
  ]
  for (const id of variants) {
    const base = id === 'gate_w' ? 'gate' : id,
      d = artDefinition(base),
      t = spriteTemplate(base, d.w, d.h)
    registry.push(`  ${id}: {`)
    for (let level = 1; level <= (scenicSizes[id] ? 1 : 5); level++) {
      const commands = topdownArt(base, level, id === 'gate_w')
      const surface = ck.MakeSurface(t.width, t.height)
      if (!surface) throw new Error('Cannot create art surface')
      const canvas = surface.getCanvas(),
        paint = new ck.Paint()
      paint.setAntiAlias(false)
      canvas.clear(ck.TRANSPARENT)
      canvas.translate(t.ax, t.ay)
      for (const c of commands) {
        paint.setColor(ck.parseColorString(c.color))
        if (c.kind === 'polygon') {
          const p = ck.Path.MakeFromSVGString('M' + c.points.map(a => a.join(' ')).join('L') + 'Z')
          if (p) {
            canvas.drawPath(p, paint)
            p.delete()
          }
        } else if (c.kind === 'circle') canvas.drawCircle(c.x, c.y, c.r, paint)
        else if (c.kind === 'ellipse') canvas.drawOval(ck.XYWHRect(c.x, c.y, c.w, c.h), paint)
        else canvas.drawRect(ck.XYWHRect(c.x, c.y, c.w, c.h), paint)
      }
      surface.flush()
      const image = surface.makeImageSnapshot(),
        bytes = image.encodeToBytes()
      if (!bytes) throw new Error(`Cannot encode ${id}`)
      const file = `${id}_L${level}.png`
      fs.writeFileSync(path.join(target, file), bytes)
      registry.push(
        `    ${level}: {src: require('../../../assets/v5/buildings/${file}'), w:${t.width}, h:${t.height}, ax:${t.ax}, ay:${t.ay}, scale:1, smooth:false},`,
      )
      manifest[`${id}:${level}`] = {
        file,
        level,
        id: base,
        orientation: id === 'gate_w' ? 'west' : base === 'gate' ? 'north' : undefined,
        sockets: ['cdu', 'cracker', 'flare'].includes(base)
          ? { emitter: { x: t.ax + buildingSocket(base).x, y: t.ay + buildingSocket(base).y } }
          : undefined,
        ...t,
      }
      image.delete()
      paint.delete()
      surface.delete()
    }
    registry.push('  },')
  }
  registry.push('}')
  fs.writeFileSync(path.join(root, 'src/v4/render/v5Buildings.ts'), registry.join('\n') + '\n')
  fs.writeFileSync(path.join(target, 'manifest.json'), JSON.stringify(manifest, null, 2) + '\n')
  console.log(
    `V5: exported ${Object.keys(manifest).length} fixed-frame sprites, all at 1 art px = 1 world unit`,
  )
}
main().catch(e => {
  console.error(e)
  process.exitCode = 1
})
