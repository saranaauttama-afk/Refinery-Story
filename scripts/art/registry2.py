# Writes src/v4/render/spriteImages.ts from assets/v4/sprites/meta.json (made by build_set.py).
import json, os
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..') if os.path.exists(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..', 'app.json')) else '/home/claude/refinery-story'
meta = json.load(open(f'{R}/assets/v4/sprites/meta.json'))
ids = {}
for k, m in sorted(meta.items()):
    id, tier = k.split(':'); ids.setdefault(id, []).append((int(tier), m))
rows = []
for id, tiers in ids.items():
    parts = [f"{t}: img(require('../../../assets/v4/sprites/{id}_L{t}.png'), {m['w']}, {m['h']}, {m['ax']}, {m['ay']}, {m['scale']}{', true' if m.get('smooth') else ''})" for t, m in sorted(tiers)]
    rows.append(f"  {id}: {{\n    " + ",\n    ".join(parts) + ",\n  },")
ts = f"""// PixelLab sprites, generated by scripts/art/registry2.py from assets/v4/sprites/meta.json.
// Each image: size at 2x, the footprint centre inside it (ax, ay) and the scale that makes its
// ground slab fill the footprint. Buildings without an entry use code-drawn sprites.
export type Tier = 1 | 2 | 3 | 4 | 5
export type SpriteImage = {{
  src: number
  w: number
  h: number
  ax: number
  ay: number
  scale: number
  /** Hi-res art: scale with linear filtering instead of nearest-neighbour. */
  smooth: boolean
}}
const img = (
  src: number,
  w: number,
  h: number,
  ax: number,
  ay: number,
  scale: number,
  smooth = false,
): SpriteImage => ({{ src, w, h, ax, ay, scale, smooth }})
export const spriteImages: Record<string, Partial<Record<Tier, SpriteImage>>> = {{
{chr(10).join(rows)}
}}
/** The image tier a building at this level uses: its own level, else the nearest lower one. */
export function spriteTierFor(id: string, level: number): Tier | undefined {{
  const set = spriteImages[id]
  if (!set) return undefined
  for (let t = Math.min(5, Math.max(1, level)); t >= 1; t--) if (set[t as Tier]) return t as Tier
  return undefined
}}
export function spriteImageFor(id: string, level: number): SpriteImage | undefined {{
  const tier = spriteTierFor(id, level)
  return tier ? spriteImages[id][tier] : undefined
}}
/** Every image the yard needs loaded, in a fixed order (one hook each). */
export const allSpriteImages = Object.entries(spriteImages).flatMap(([id, set]) =>
  Object.entries(set).map(([tier, im]) => ({{ key: `${{id}}:${{tier}}`, img: im! }})),
)
"""
open(f'{R}/src/v4/render/spriteImages.ts', 'w').write(ts); print(len(rows), 'ids')
