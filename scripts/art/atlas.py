# Packs every world/ambient sprite into one atlas and writes src/v4/render/worldAtlas.ts.
import json, os, numpy as np
from PIL import Image, ImageOps
R='/home/claude/refinery-story'
items={}
def add(name,im,ax=None,ay=None):
    im=im.convert('RGBA'); items[name]=(im, im.width/2 if ax is None else ax, im.height if ay is None else ay)
def T(d,n): return Image.open(f'r4/{d}/tile_{n}.png').convert('RGBA')
GS=[T('grass_sand',i) for i in range(16)]; SW=[T('sand_water',i) for i in range(16)]
ref=np.array(GS[15])[:16]; rm=ref[ref[:,:,3]>0][:,:3].mean(0)
def match(t):
    a=np.array(t).astype(float); m=a[:,:,3]>0; cm=a[m][:,:3].mean(0); a[m,:3]=np.clip(a[m,:3]*(rm/cm),0,255); return Image.fromarray(a.astype('uint8'))
def dull(t,f=0.93):
    a=np.array(t).astype(float); m=a[:,:,3]>0; g=a[m][:,:3].mean(1,keepdims=True); a[m,:3]=np.clip((a[m,:3]*0.85+g*0.15)*f,0,255); return Image.fromarray(a.astype('uint8'))
for i,n in enumerate([0,8]): add(f'grass{i}',match(T('ground',n)),0,0)
add('flower0',match(T('ground',1)),0,0)
for i,n in enumerate([0,8]): add(f'locked{i}',dull(match(T('ground',n))),0,0)
for i in range(16): add(f'gs{i}',GS[i],0,0); add(f'sw{i}',SW[i],0,0)
# roads: edge mask -> tile; squash the 1:1 diamonds to 2:1
rules=json.load(open('r5/road/meta.json'))['tile_rules']['tiles']
seen=set()
for k,v in sorted(rules.items(),key=lambda kv:int(kv[0].split('_')[1])):
    m=v['mask']
    if m in seen: continue
    seen.add(m); im=Image.open(f'r5/road/{k}.png').convert('RGBA'); add(f'road{m}',im.resize((64,32),Image.NEAREST),0,0)
P='pick'
for g,n in [('tree',7),('palm',5),('bush',4),('rocks',4),('islet',4),('mountain',2),('cloud',5),('gull',3),('fish',1)]:
    for i in range(n):
        im=Image.open(f'{P}/{g}_{i}.png').convert('RGBA'); im=im.crop(im.getbbox())
        add(f'{g}{i}',im,im.width/2,im.height-2 if g in ('tree','palm','bush','rocks') else im.height/2)
f=Image.open(f'{P}/fence_0.png').convert('RGBA'); f=f.crop(f.getbbox()); add('fence0',f,f.width/2,f.height-3); add('fence1',ImageOps.mirror(f),f.width/2,f.height-3)
dirs={'se':'south-east','ne':'north-east','nw':'north-west','sw':'south-west'}
for v in ['crude','product','car','ship','fishboat']:
    for k,d in dirs.items():
        im=Image.open(f'r7/{v}/rotation_urls_{d}.png').convert('RGBA'); bb=im.getbbox(); im=im.crop(bb)
        add(f'{v}_{k}',im,im.width/2,im.height*0.62)
def frames(path,fw,fh,n,prefix,ax,ay):
    sh=Image.open(path).convert('RGBA'); cols=sh.width//fw
    for i in range(n): add(f'{prefix}{i}',sh.crop(((i%cols)*fw,(i//cols)*fh,(i%cols+1)*fw,(i//cols+1)*fh)),ax,ay)
frames('r8/smoke/chimney-smoke.png',32,32,16,'smoke',14,31)
frames('r8/sparkle/level-up-sparkle.png',48,48,8,'spark',24,24)
# shelf pack
names=sorted(items,key=lambda n:-items[n][0].height); W=1024; x=y=rowh=0; rects={}
for n in names:
    im=items[n][0]
    if x+im.width+1>W: x=0; y+=rowh+1; rowh=0
    rects[n]=(x,y); x+=im.width+1; rowh=max(rowh,im.height)
H=y+rowh; atlas=Image.new('RGBA',(W,H),(0,0,0,0))
for n,(px,py) in rects.items(): atlas.alpha_composite(items[n][0],(px,py))
os.makedirs(f'{R}/assets/v4/world',exist_ok=True); atlas.save(f'{R}/assets/v4/world/atlas.png',optimize=True)
lines=["// Generated by scripts/art/atlas.py: every world/ambient sprite packed into one image.",
"// [x, y, w, h, ax, ay] in atlas pixels; (ax, ay) is the sprite's anchor.",
"export const worldAtlasSrc = require('../../../assets/v4/world/atlas.png')",
"export const atlas: Record<string, readonly [number, number, number, number, number, number]> = {"]
for n in sorted(rects):
    im,ax,ay=items[n]; px,py=rects[n]; lines.append(f"  {n}: [{px}, {py}, {im.width}, {im.height}, {round(ax,1)}, {round(ay,1)}],")
lines.append("}")
# average deep-water colour for the world backdrop
a=np.array(SW[0])[:16]; c=a[a[:,:,3]>0][:,:3].mean(0).astype(int); lines.append(f"export const seaColor = '#{c[0]:02x}{c[1]:02x}{c[2]:02x}'")
open(f'{R}/src/v4/render/worldAtlas.ts','w').write("\n".join(lines)+"\n"); print(W,H,len(rects))
