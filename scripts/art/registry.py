# Writes src/v4/render/spriteImages.ts from the PNGs in assets/v4/sprites.
import os, re
from PIL import Image
R = os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..')
N = dict(cdu=4, crudeTank=4, blend=4, tank=2, hydro=4, reformer=5, cracker=6, tower=6, loading=4, lab=2,
         control=3, canteen=3, pipe=2, tree=2, lamp=2, sign=2, flag=2, goldTree=2, goldSign=2, legend=2,
         awardproduct=2, awardsafety=2, awardeco=2, awardrefinery=2)
rows = {}
for f in sorted(os.listdir(f'{R}/assets/v4/sprites')):
    m = re.match(r'(\w+)_L([135])\.png$', f)
    if not m: continue
    w, h = Image.open(f'{R}/assets/v4/sprites/{f}').size
    rows.setdefault(m[1], []).append(f"{m[2]}: at(require('../../../assets/v4/sprites/{f}'), {w}, {h}, {N[m[1]]})")
body = '\n'.join(f"  {k}: {{ {', '.join(v)} }}," for k, v in rows.items())
t = open(f'{R}/src/v4/render/spriteImages.ts').read()
t = re.sub(r'(export const spriteImages[^\n]*\n)(.*?)(\n\})', lambda m: m[1] + body + m[3], t, flags=re.S)
t = t.replace('// PixelLab sprites (pilot).', '// PixelLab sprites (generated by art/registry.py).')
open(f'{R}/src/v4/render/spriteImages.ts', 'w').write(t)
print(body)
