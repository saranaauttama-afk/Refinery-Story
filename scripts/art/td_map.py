"""Single-image world map -> assets/v4/td/map.png + src/v4/render/tdMap.ts.

usage: python3 scripts/art/td_map.py art-src/gpt/topdown/map_v1.png
The source is ChatGPT art drawn 2x (each art pixel = 2 image px). The flat grey yard
block (32 x 24 tiles at 32 px) is found automatically; its top-left becomes tile 0,0.
"""
import sys, json
from PIL import Image

src = Image.open(sys.argv[1]).convert('RGB')
W, H = src.size
YARD = (206, 207, 207)
# Find the yard: the biggest run of the flat grey on the middle rows / columns.
def near(p, q, t=4):
    return all(abs(a - b) <= t for a, b in zip(p, q))
def run(get, start, n):
    a = b = start
    while a > 0 and near(get(a - 1), YARD): a -= 1
    while b < n - 1 and near(get(b + 1), YARD): b += 1
    return a, b
# Start from the middle of the biggest grey blob near the picture centre.
seed = max(((x, y) for x in range(W // 4, 3 * W // 4, 16) for y in range(H // 4, 3 * H // 4, 16)
            if near(src.getpixel((x, y)), YARD)),
           key=lambda p: (lambda r: r[1] - r[0])(run(lambda x: src.getpixel((x, p[1])), p[0], W)))
x0, x1 = run(lambda x: src.getpixel((x, seed[1])), seed[0], W)
cx = (x0 + x1) // 2
y0, y1 = run(lambda y: src.getpixel((cx, y)), seed[1], H)
print('yard px', x0, y0, x1, y1, 'tiles', (x1 - x0 + 1) / 32, (y1 - y0 + 1) / 32)

half = src.resize((W // 2, H // 2), Image.NEAREST)
half.save('assets/v4/td/map.png', optimize=True)

# Sea glints: tiles whose centre and corners are open water.
def water(p):
    r, g, b = p
    return b > 200 and r < 60 and 100 < g < 190
glints = []
for ty in range(-(y0 // 32), (H - y0) // 32):
    for tx in range(-(x0 // 32), (W - x0) // 32):
        px, py = x0 + tx * 32, y0 + ty * 32
        pts = [(px + 4, py + 4), (px + 28, py + 4), (px + 4, py + 28), (px + 28, py + 28), (px + 16, py + 16)]
        if all(0 <= a < W and 0 <= b < H and water(src.getpixel((a, b))) for a, b in pts):
            glints.append((tx, ty))
print('water tiles', len(glints))
import random
random.seed(7)
pick = sorted(random.sample(glints, min(160, len(glints))))
out = f"""// Generated by scripts/art/td_map.py — do not edit by hand.
// The world map is one picture; the yard's top-left corner (tile 0,0) sits at (x, y)
// in world px and every image pixel covers `k` world px.
export const tdMapSrc = require('../../../assets/v4/td/map.png')
export const tdMap = {{
  x: {-x0},
  y: {-y0},
  w: {W},
  h: {H},
  k: 2,
  /** Open-water tiles for sea glints. */
  water: {json.dumps([list(p) for p in pick])} as [number, number][],
}}
"""
open('src/v4/render/tdMap.ts', 'w').write(out)
